def seed(apps, schema_editor=None):
    Job = apps.get_model('careers', 'JobOpening')
    Step = apps.get_model('careers', 'FormStep')
    Q = apps.get_model('careers', 'FormQuestion')
    for spec in (TEACHER, SUPERVISOR):
        data = dict(spec['job'], date_posted=datetime.date(2026, 11, 20), valid_through=datetime.date(2027, 6, 30))
        if Job.objects.filter(slug=data['slug']).exists():
            continue
        job = Job.objects.create(**data)
        for i, (title, questions) in enumerate(spec['steps'], 1):
            step = Step.objects.create(job=job, order=i, title=title)
            for j, q in enumerate(questions, 1):
                Q.objects.create(job=job, step=step, order=j, **q)
